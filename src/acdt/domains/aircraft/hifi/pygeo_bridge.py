"""FFD of the flying-wing loft for pyGeo. pyGeo, ADflow and TACS stay outside this process.

The loft is the same surface ``wing_bl.build_patches`` already writes for pyHyp. This module
adds one Plot3D volume, the axis-aligned box of that surface, grown so every loft point sits
inside it. A generated script embeds those points with ``DVGeometry``. acdt does not import
pyGeo. With no design variable set, the embedded points are the check that the box contains
the loft. That check is not an ADflow solution and not a TACS solution.
"""
from __future__ import annotations

import json
from pathlib import Path

import numpy as np

from .wing_bl import PATCH_NAMES, write_plot3d_surface

# PRESSUPOSTO: the FFD is the axis-aligned bound of the loft, not a fitted camber box.
# Five percent of each side, and at least 1 mm, keeps the surface off the spline boundary.
FFD_MARGIN = 0.05
FFD_MARGIN_MIN_M = 1.0e-3
FFD_SHAPE = (6, 8, 4)


def surface_points(patches: dict) -> np.ndarray:
    """Unique loft nodes, shape (N, 3). Shared edges are stored once."""
    chunks = [np.asarray(patches[name], dtype=np.float64).reshape(-1, 3) for name in PATCH_NAMES]
    pts = np.vstack(chunks)
    return np.unique(np.round(pts, decimals=12), axis=0)


def ffd_lattice(points: np.ndarray, shape: tuple[int, int, int] = FFD_SHAPE,
                margin: float = FFD_MARGIN) -> np.ndarray:
    """One-block FFD, shape (ni, nj, nk, 3). i is x, j is y, k is z."""
    ni, nj, nk = (int(v) for v in shape)
    if min(ni, nj, nk) < 2:
        raise ValueError("an FFD block needs at least two points on each side")
    pts = np.asarray(points, dtype=np.float64)
    if pts.ndim != 2 or pts.shape[1] != 3 or len(pts) == 0:
        raise ValueError("points must be (N, 3) and non-empty")
    lo = pts.min(axis=0)
    hi = pts.max(axis=0)
    span = np.maximum(hi - lo, FFD_MARGIN_MIN_M)
    pad = np.maximum(margin * span, FFD_MARGIN_MIN_M)
    lo = lo - pad
    hi = hi + pad
    axes = [np.linspace(lo[d], hi[d], n) for d, n in enumerate((ni, nj, nk))]
    grid = np.empty((ni, nj, nk, 3), dtype=np.float64)
    grid[..., 0] = axes[0][:, None, None]
    grid[..., 1] = axes[1][None, :, None]
    grid[..., 2] = axes[2][None, None, :]
    return grid


def points_inside(points: np.ndarray, grid: np.ndarray) -> dict:
    """Strictly inside the axis-aligned FFD. A point on the face is not inside."""
    lo = np.array([grid[..., d].min() for d in range(3)])
    hi = np.array([grid[..., d].max() for d in range(3)])
    pts = np.asarray(points, dtype=np.float64)
    inside = np.all((pts > lo) & (pts < hi), axis=1)
    return {"n_points": int(len(pts)), "n_inside": int(inside.sum()),
            "all_inside": bool(inside.all()),
            "lo_m": lo.tolist(), "hi_m": hi.tolist()}


def write_plot3d_volume(grid: np.ndarray, path: Path) -> None:
    """ASCII Plot3D, one block, Fortran order (i fastest). pyGeo asks for that order."""
    grid = np.asarray(grid, dtype=np.float64)
    ni, nj, nk, nd = grid.shape
    if nd != 3:
        raise ValueError("volume grid last axis must be x, y, z")
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="ascii", newline="\n") as f:
        f.write("1\n")
        f.write(f"{ni} {nj} {nk}\n")
        for dim in range(3):
            for k in range(nk):
                for j in range(nj):
                    for i in range(ni):
                        f.write(f"{grid[i, j, k, dim]:.16g}\n")


def write_pygeo_script(path: Path) -> None:
    """Container script. Imports pyGeo only. Does not import acdt, ADflow or TACS."""
    shape = repr(list(FFD_SHAPE))
    text = f'''"""Generated by acdt. This process does not load the acdt package. pyGeo only."""
import json
import numpy as np

print("STAGE import", flush=True)
from pygeo import DVGeometry
print("STAGE imported", flush=True)


def read_surface(path):
    with open(path, encoding="ascii") as fh:
        n_patch = int(next(fh).split()[0])
        sizes = []
        while len(sizes) < 3 * n_patch:
            sizes.extend(int(tok) for tok in next(fh).split())
        pts = []
        for b in range(n_patch):
            il, jl, nk = sizes[3 * b:3 * b + 3]
            if nk != 1:
                raise SystemExit("surface block k is %s" % nk)
            xyz = np.empty((il, jl, 3), dtype=np.float64)
            for dim in range(3):
                for j in range(jl):
                    for i in range(il):
                        xyz[i, j, dim] = float(next(fh).split()[0])
            pts.append(xyz.reshape(-1, 3))
    return np.unique(np.round(np.vstack(pts), decimals=12), axis=0)


pts = read_surface("surface.xyz")
geo = DVGeometry("ffd.xyz")
geo.addPointSet(pts, "loft")
out = np.asarray(geo.update("loft"), dtype=np.float64)
if out.shape != pts.shape:
    raise SystemExit("updated shape %s is not %s" % (out.shape, pts.shape))
move = np.linalg.norm(out - pts, axis=1)
meta = {{
    "status": "ok",
    "n_points": int(pts.shape[0]),
    "ffd_shape": {shape},
    "max_point_move_m": float(move.max()),
    "embedded": True,
    "adflow": "nao_avaliado",
    "tacs": "nao_avaliado",
    "reason": "Sem variavel de projecto o ponto embutido tem de coincidir com o loft. Isto nao e uma solucao de escoamento nem de estrutura.",
}}
with open("pygeo_meta.json", "w", encoding="utf-8") as fh:
    json.dump(meta, fh, indent=1)
print("PYGEO_DONE", float(move.max()), flush=True)
'''
    Path(path).write_text(text, encoding="utf-8", newline="\n")


def write_case(work: Path, patches: dict) -> dict:
    """Surface, FFD and the container script. Does not start pyGeo."""
    work = Path(work)
    work.mkdir(parents=True, exist_ok=True)
    pts = surface_points(patches)
    grid = ffd_lattice(pts)
    inside = points_inside(pts, grid)
    if not inside["all_inside"]:
        raise ValueError("the FFD box does not contain every loft point")
    write_plot3d_surface(patches, work / "surface.xyz")
    write_plot3d_volume(grid, work / "ffd.xyz")
    write_pygeo_script(work / "pygeo_ffd.py")
    record = {
        "surface": "surface.xyz",
        "ffd": "ffd.xyz",
        "script": "pygeo_ffd.py",
        "n_points": int(len(pts)),
        "ffd_shape": list(FFD_SHAPE),
        "margin": FFD_MARGIN,
        "pressuposto": (
            "PRESSUPOSTO: o FFD e a caixa alinhada aos eixos do loft, aumentada 5 % em cada lado "
            "(no minimo 1 mm). Nao e uma caixa ajustada a curvatura. Nao ha variavel de projecto."
        ),
        "inside": inside,
        "adflow": "nao_avaliado",
        "tacs": "nao_avaliado",
    }
    (work / "pygeo_case.json").write_text(json.dumps(record, indent=1), encoding="utf-8")
    return record


def container_shell() -> str:
    """Command that runs inside the image. The G1 PRoot notes apply: one rank, tcp on lo.

    acdt does not run this itself unless udocker is on PATH. The Windows process does not
    import pyGeo either way.
    """
    return (
        "source /home/mdolabuser/.bashrc_mdolab && "
        "export OMP_NUM_THREADS=1 MKL_NUM_THREADS=1 OPENBLAS_NUM_THREADS=1 && "
        "mpirun --mca btl tcp,self --mca btl_vader_single_copy_mechanism none "
        "--mca oob_tcp_if_include lo --mca btl_tcp_if_include lo -np 1 python pygeo_ffd.py"
    )
